// Helper to generate Lagrangian scatter points around a center
function generateLagrangianParticles(centerLat: number, centerLng: number, spreadDeg: number, count: number): {
  id: number;
  lat: number;
  lng: number;
  ageHours: number;
  massFractionRemaining: number;
  status: 'active' | 'evaporated' | 'beached';
}[] {
  const particles = [];
  for (let i = 0; i < count; i++) {
    const angle = Math.random() * Math.PI * 2;
    const radius = Math.sqrt(Math.random()) * spreadDeg;
    // Stretch along major drift axis
    const latOffset = radius * Math.cos(angle) * 0.7;
    const lngOffset = radius * Math.sin(angle) * 1.3;
    particles.push({
      id: i + 1,
      lat: Number((centerLat + latOffset).toFixed(6)),
      lng: Number((centerLng + lngOffset).toFixed(6)),
      ageHours: Number((Math.random() * 6).toFixed(1)),
      massFractionRemaining: Number((0.75 + Math.random() * 0.25).toFixed(2)),
      status: 'active' as const,
    });
  }
  return particles;
}
